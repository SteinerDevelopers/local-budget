/// Look up one glyph (already upper-cased); null when unsupported — the
/// rasteriser paints a hollow box for those so gaps are visible, never a
/// silent skip that would shift the text.
List<String>? glyphFor(String upperChar) {
  final g = _latin[upperChar];
  if (g != null) return g;
  // Cyrillic lower-case maps to upper-case at -0x20 for the whole block
  // (plus Ё/ё which Dart's toUpperCase already handled).
  return _cyrillic[upperChar.toUpperCase()];
}

